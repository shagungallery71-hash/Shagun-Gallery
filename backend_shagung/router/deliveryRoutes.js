// Create a Set for O(1) lookup
const PINCODE_SET = new Set(SERVICEABLE_PINCODES);

// =============================================================================
// CHECK PINCODE AVAILABILITY - GET /api/delivery/check/:pincode
// =============================================================================
deliveryRouter.get('/check/:pincode', async (req, res) => {
    try {
        const { pincode } = req.params;

        // Validate pincode format (6 digits)
        if (!pincode || !/^\d{6}$/.test(pincode)) {
            return res.status(400).json({
                success: false,
                available: false,
                message: 'Invalid PIN code format. Must be 6 digits.'
            });
        }

        const isAvailable = PINCODE_SET.has(pincode);

        // Calculate estimated delivery date (3-7 days based on pincode)
        const daysToDeliver = isAvailable ? (parseInt(pincode.charAt(0)) % 5) + 3 : 0;
        const deliveryDate = isAvailable
            ? new Date(Date.now() + (daysToDeliver * 24 * 60 * 60 * 1000))
                .toLocaleDateString('en-US', { weekday: 'long', month: 'short', day: 'numeric' })
            : null;

        res.json({
            success: true,
            available: isAvailable,
            pincode,
            message: isAvailable
                ? `Delivery available to ${pincode}`
                : 'Delivery not available to this location',
            deliveryInfo: isAvailable ? {
                estimatedDays: daysToDeliver,
                estimatedDate: deliveryDate,
                shippingCost: daysToDeliver <= 4 ? 0 : 49, // Free shipping for faster delivery zones
                expressAvailable: daysToDeliver <= 4
            } : null
        });
    } catch (error) {
        console.error('Pincode Check Error:', error);
        res.status(500).json({
            success: false,
            available: false,
            message: 'Failed to check delivery availability'
        });
    }
});

